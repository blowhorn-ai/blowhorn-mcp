/*
 * Generates hosted/schemas/generated/org-required.schema.json, the JSON Schema
 * of Cloud's organization-selection-required answer, from the vendored
 * meshery/schemas OpenAPI document (OrganizationSelectionRequiredError and the
 * OrganizationSelectionChoice it refers to, in
 * schemas/constructs/v1beta2/core/api.yml). The Worker imports the generated
 * JSON, so it needs no YAML parser at runtime; `yaml` is a dev dependency used
 * only here. Nothing in the output is typed by hand: it is the vendored
 * definitions with the Go codegen extensions (x-*) dropped and the local
 * $refs pointed at $defs. `make hosted-check` fails when the checked-in file
 * differs from what this regenerates.
 *
 * Run by `make hosted-schemas-refresh` after a refresh, or by hand:
 *   node hosted/scripts/org-required-schema.js
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";
import { HOSTED, readSources, vendored } from "./vendor.js";

export const API_FILE = "schemas/constructs/v1beta2/core/api.yml";
export const ROOT = "OrganizationSelectionRequiredError";
export const OUT = path.join(HOSTED, "schemas", "generated", "org-required.schema.json");
const LOCAL_REF = /^#\/components\/schemas\/([A-Za-z0-9_]+)$/;

/** `node` with every `x-*` extension removed and every local component $ref pointed at `#/$defs/<name>`; collects the names referred to into `used`. */
function convert(node, used) {
  if (Array.isArray(node)) return node.map((n) => convert(n, used));
  if (!node || typeof node !== "object") return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith("x-")) continue;
    if (k === "$ref") {
      const m = typeof v === "string" ? LOCAL_REF.exec(v) : null;
      if (!m) throw new Error(`${API_FILE}: $ref ${JSON.stringify(v)} is not a local components/schemas reference`);
      used.add(m[1]);
      out[k] = `#/$defs/${m[1]}`;
    } else out[k] = convert(v, used);
  }
  return out;
}

/** The JSON Schema for ROOT, derived from the OpenAPI document `yamlText` and the commit it came from. */
export function generate(yamlText, { repo, ref } = {}) {
  const schemas = parse(yamlText)?.components?.schemas;
  if (!schemas?.[ROOT]) throw new Error(`${API_FILE}: components.schemas.${ROOT} is missing`);
  const used = new Set();
  const root = convert(schemas[ROOT], used);
  const defs = {};
  for (const name of [...used]) {
    // used grows while converting, so a def's own refs are followed too.
    if (!schemas[name]) throw new Error(`${API_FILE}: components.schemas.${name} is missing`);
    defs[name] = convert(schemas[name], used);
  }
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    title: ROOT,
    $comment: `GENERATED by hosted/scripts/org-required-schema.js from ${repo ?? "meshery/schemas"}@${ref ?? "?"} ${API_FILE}. Do not edit; run make hosted-schemas-refresh.`,
    ...root,
    $defs: defs,
  };
}

/** The pinned meshery/schemas SOURCES.json entry and the vendored api.yml text. */
export function vendoredApi(vendor) {
  const entry = readSources(vendor).sources.find((s) => s.repo === "meshery/schemas");
  if (!entry) throw new Error("SOURCES.json: no meshery/schemas source");
  return { entry, text: fs.readFileSync(vendored(entry.dir, API_FILE, vendor), "utf8") };
}

/** The checked-in file's expected text, regenerated from the vendored YAML. */
export function expected(vendor) {
  const { entry, text } = vendoredApi(vendor);
  return JSON.stringify(generate(text, entry), null, 2) + "\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, expected());
  process.stdout.write(`wrote ${path.relative(HOSTED, OUT)}\n`);
}
